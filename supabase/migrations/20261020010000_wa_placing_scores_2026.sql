-- Ohne Importer-Angabe zählen nur Finals (F) mit ihrer Platzierung.
create or replace function public.race_type(p_race text) returns text
language sql immutable as $$
  select case when p_race is null or p_race in ('', 'F') then 'F' end
$$;

create or replace view public.result_points with (security_invoker = true) as
with base as (
  select
    r.*,
    s.id as season_id,
    s.perf_threshold, s.perf_factor, s.placing_factor,
    coalesce(d.factor, 0) as discipline_factor,
    -- Cross: fester Performance Score nach Platz ersetzt den (fehlenden) Result Score
    coalesce(
      (select ps.points from public.placing_scores ps
       where ps.placing_table = d.performance_table and ps.category = r.category
         and ps.race_type = 'F' and ps.place = r.place and public.race_type(r.race) = 'F'),
      r.result_score
    ) as effective_score,
    coalesce((
      select max(ps.points) from public.placing_scores ps
      where ps.placing_table = any (d.placing_tables)
        and ps.category = r.category
        and ps.race_type = coalesce(r.placing_round, public.race_type(r.race))
        and ps.place = coalesce(r.placing_place, r.place)
    ), 0) as placing_base
  from public.results r
  join public.seasons s on extract(year from r.date) = s.year
  left join public.disciplines d on d.name = r.discipline
)
select
  id as result_id,
  season_id,
  athlete_id,
  date,
  competition,
  discipline,
  category,
  race,
  place,
  mark,
  effective_score as result_score,
  discipline_factor,
  round(greatest(0, coalesce(effective_score, 0) - perf_threshold) * perf_factor * discipline_factor, 1)
    as performance_points,
  round(placing_base * placing_factor * discipline_factor, 1) as placing_points,
  round(greatest(0, coalesce(effective_score, 0) - perf_threshold) * perf_factor * discipline_factor, 1)
    + round(placing_base * placing_factor * discipline_factor, 1) as total_points,
  wa_race,
  wa_place,
  placing_round,
  placing_place
from base;

